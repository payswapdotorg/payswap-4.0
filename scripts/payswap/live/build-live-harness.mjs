#!/usr/bin/env node
/**
 * PaySwap P2 live harness 构建器 —— 把真实 law 模块从源码编译为单文件 CJS
 * bundle（`packages/desktop/.live-harness/harness-bundle.cjs`），供
 * `scripts/payswap/live/main.cjs`（Electron main 入口）require。
 *
 * 编译面（全部为生产源码 —— 零替身）：
 * - desktop main 的 payswap 装配：accountRuntimeWiring / pspCredentialKeyStore /
 *   accountWarmup / accountReaderBridgeEntry（Electron 结构面保持 external ——
 *   bundle 在真实 Electron main 进程内运行，require("electron") 由运行时解析）；
 * - services 的账户运行时与路径规则（@zcode/services/node 依赖图的一部分，
 *   经源文件相对引入进入同一 bundle）；
 * - shared 的 payswap 法则（zod 双端校验、桥协议、连接法则 —— 经
 *   @zcode/shared/payswap 进入 bundle）。
 *
 * bundle 后处理（打包侧修补 —— 永不改生产源码；架构师 2026-11-15 裁决：
 * 生产 terminalService 的 `createRequire(import.meta.url)` 是合法 ESM 形态，
 * 不是缺陷；CJS bundle 化产生的 `import.meta` 空对象 shim 才是问题）：
 * 1. createRequire 修补：`(0, import_x.createRequire)(import_meta.url)` →
 *    `(...)(__filename)`（bundle 内单点；每次重建后由本脚本重打并验证 ——
 *    补丁未生效即 fail loud）。
 * 2. node:sqlite 改写的运行时修补由 main.cjs 的 resolve 钩子承担（本脚本
 *    只负责编译；stub 是 throws-on-use）。
 *
 * 用法（live 验收 VM 内，repo 根目录）：
 *   node scripts/payswap/live/build-live-harness.mjs
 *
 * 前置：`pnpm install --frozen-lockfile` 已完成（workspace 链接 + desktop 的
 * tsup 依赖就位）。输出目录 `.live-harness/` 是构建产物（不入 Git）。
 */

import { mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// 本脚本位于 <root>/scripts/payswap/live/ —— 文件路径起算四级上行才是仓库根
// （file → live → payswap → scripts → root）。三级上行止于 scripts/，会把
// OUT_DIR 钉到 scripts/packages/desktop/.live-harness，@zcode/shared 的依赖图
// 解析随之崩塌（2026-11-17 win32 实测 6 连败根因之二）。
const REPO_ROOT = resolve(fileURLToPath(import.meta.url), "..", "..", "..", "..");
const DESKTOP_DIR = join(REPO_ROOT, "packages", "desktop");
const OUT_DIR = join(DESKTOP_DIR, ".live-harness");
const ENTRY_PATH = join(OUT_DIR, "harness-entry.mjs");
const BUNDLE_PATH = join(OUT_DIR, "harness-bundle.cjs");

// tsup 经 desktop 包解析（root devDeps 不含 tsup —— desktop 的构建链持有它）。
const desktopRequire = createRequire(join(DESKTOP_DIR, "package.json"));
const { build } = desktopRequire("tsup");

/** 生成的入口：再导出 harness 组装所需的全部真实模块（源码路径直引 —— 不经
 *  desktop 包出口，因为 desktop main 的 payswap 模块不作为包出口发布）。
 *  import specifier 一律正斜杠 —— Windows 反斜杠在 JS 字符串字面量里是转义
 *  序列（\U→U、\L→L…），esbuild 解析出的 specifier 会丢光分隔符
 *  （C:\Users\… → C:Users…，2026-11-17 win32 实测 6 连败根因）。 */
const toImportSpecifier = (p) => p.replaceAll("\\", "/");
const ENTRY_SOURCE = `// GENERATED by scripts/payswap/live/build-live-harness.mjs — do not edit.
export { createPayswapDesktopAccountRuntime } from "${toImportSpecifier(join(DESKTOP_DIR, "src/main/payswap/accountRuntimeWiring.ts"))}";
export { createPayswapPspKeyStore } from "${toImportSpecifier(join(DESKTOP_DIR, "src/main/payswap/pspCredentialKeyStore.ts"))}";
export { warmupPayswapPspRuntimeEnv } from "${toImportSpecifier(join(DESKTOP_DIR, "src/main/payswap/accountWarmup.ts"))}";
export {
  createPayswapReaderBridgePortMinter,
  adaptMessagePortMainToPayswapReaderBridgePort,
} from "${toImportSpecifier(join(DESKTOP_DIR, "src/main/payswap/accountReaderBridgeEntry.ts"))}";
export { createPayswapReaderBridgeClient } from "@zcode/shared/payswap";
export { getAppConfigDir } from "${toImportSpecifier(join(REPO_ROOT, "packages/services/src/paths.ts"))}";
`;

/** esbuild CJS 化后的 createRequire 调用形态（`import.meta` 被 shim 成空对象）：
 *  `(0, import_node_module.createRequire)(import_meta.url)` —— 变量名可漂移。 */
const CREATE_REQUIRE_SHIM_PATTERN =
  /\(\s*0\s*,\s*([A-Za-z_$][\w$]*)\.createRequire\s*\)\(\s*([A-Za-z_$][\w$]*)\.url\s*\)/g;

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(ENTRY_PATH, ENTRY_SOURCE, "utf8");

  console.log(`[build-live-harness] entry: ${ENTRY_PATH}`);
  await build({
    entry: { "harness-bundle": ENTRY_PATH },
    outDir: OUT_DIR,
    format: ["cjs"],
    platform: "node",
    target: "node20",
    // Electron 结构面（safeStorage/MessageChannelMain 等）必须在运行时由真实
    // Electron 解析 —— 绝不内联。
    external: ["electron"],
    splitting: false,
    sourcemap: false,
    clean: false,
    dts: false,
    // 入口是 .mjs —— 必须显式钉住 CJS 扩展名（否则输出可能沿用 .mjs 被当 ESM）。
    outExtension: () => ({ js: ".cjs" }),
    silent: true,
  });

  // 后处理 1：createRequire 的 import_meta shim 修补（bundle 内单点 sed）。
  const { readFile, writeFile: writeOut } = await import("node:fs/promises");
  let source = await readFile(BUNDLE_PATH, "utf8");
  let patched = 0;
  source = source.replace(CREATE_REQUIRE_SHIM_PATTERN, (_match, moduleAlias) => {
    patched += 1;
    return `(0, ${moduleAlias}.createRequire)(__filename)`;
  });
  if (patched > 0) {
    await writeOut(BUNDLE_PATH, source, "utf8");
  }

  // 验证（fail loud）：shim 形态必须清零 —— 残留即 bundle 在运行时会
  // `createRequire(undefined)` 崩（2026-11-14 的 5 连败根因）。
  const residual = source.match(CREATE_REQUIRE_SHIM_PATTERN);
  if (residual !== null) {
    throw new Error(
      `[build-live-harness] createRequire shim 修补后仍残留 ${residual.length} 处 —— 补丁模式需随 esbuild 输出形态更新（fail loud，不带病运行）`,
    );
  }

  // 验证 2：bundle 语法级可解析（vm.Script 编译检查 —— 不执行；electron
  // external 不影响 parse）。
  const { Script } = await import("node:vm");
  new Script(source, { filename: BUNDLE_PATH });

  console.log(
    `[build-live-harness] bundle: ${BUNDLE_PATH} (createRequire shim patched: ${patched}; node:sqlite handled at runtime by main.cjs resolve hook)`,
  );
}

main().catch((error) => {
  console.error("[build-live-harness] FAILED:", error && error.stack ? error.stack : error);
  process.exit(1);
});
